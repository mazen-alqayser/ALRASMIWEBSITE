// RTL Languages
const rtlLanguages = ['ar'];

// Get saved language or default to Arabic
function getCurrentLanguage() {
    return localStorage.getItem('alrasmi_lang') || 'ar';
}

// Switch language
function switchLanguage(lang) {
    if (!translations[lang]) return;

    localStorage.setItem('alrasmi_lang', lang);

    // Set direction
    const isRTL = rtlLanguages.includes(lang);
    document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);

    // Update font family
    if (isRTL) {
        document.body.style.fontFamily = "'Cairo', sans-serif";
    } else if (lang === 'en') {
        document.body.style.fontFamily = "'Poppins', sans-serif";
    } else {
        document.body.style.fontFamily = "'Cairo', 'Poppins', sans-serif";
    }

    // Update all text elements
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    // Update select options
    const select = document.querySelector('#contact select');
    if (select) {
        const options = select.querySelectorAll('option');
        if (options[0]) options[0].textContent = translations[lang].form_select || '';
    }

    // Update current language display
    const langNames = { ar: 'العربية', en: 'English', hi: 'हिन्दी', bn: 'বাংলা' };
    const currentLangEl = document.getElementById('currentLang');
    if (currentLangEl) currentLangEl.textContent = langNames[lang];

    // Update active language option
    document.querySelectorAll('.lang-option').forEach(opt => {
        opt.classList.toggle('active-lang', opt.getAttribute('data-lang') === lang);
    });

    // Close mobile menu if open
    const mobileMenu = document.getElementById('mobileMenu');
    if (mobileMenu) mobileMenu.classList.remove('active');
    const mobileOverlay = document.getElementById('mobileOverlay');
    if (mobileOverlay) mobileOverlay.classList.remove('active');

    // Close language dropdown
    const langDropdown = document.getElementById('langDropdown');
    if (langDropdown) langDropdown.classList.remove('active');

    // Re-initialize AOS animations
    if (typeof AOS !== 'undefined') {
        setTimeout(() => AOS.refresh(), 100);
    }
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', () => {
    switchLanguage(getCurrentLanguage());
});
